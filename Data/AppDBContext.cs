using System.Data;
using Microsoft.EntityFrameworkCore;
using TANA.Models;

namespace TANA.Data
{
    public class AppDBContext : DbContext
    {
        public DbSet<Audits> Audits { get; set; } = null!;

        public DbSet<BankAccount> BankAccount { get; set; } = null!;

        public DbSet<Beneficiaries> Beneficiaries { get; set; } = null!;

        public DbSet<Employment> Employment { get; set; } = null!;

        public DbSet<InvestmentName> InvestmentName { get; set; } = null!;

        public DbSet<Investments> Investments { get; set; } = null!;

        public DbSet<Permissions> Permissions { get; set; } = null!;

        public DbSet<ProductName> ProductName { get; set; } = null!;

        public DbSet<Roles> Roles { get; set; } = null!;

        public DbSet<Users> Users { get; set; } = null!;

        public DbSet<Customers> Customers { get; set; } = null!;

        public DbSet<Otp> Otp { get; set; } = null!;

        public DbSet<QueryNumCount> NumCount { get; set; } = null!;
        public DbSet<QueryLabelValue> LabelValue { get; set; } = null!;
        public DbSet<QueryLabelValueCount> LabelValueCount { get; set; } = null!;
        public DbSet<QueryValueCount> ValueCount { get; set; } = null!;

        public AppDBContext(DbContextOptions<AppDBContext> options)
            : base(options) { }

        public AppDBContext() { }

        protected override void OnConfiguring(DbContextOptionsBuilder optionsBuilder) { }

        protected override void OnModelCreating(ModelBuilder builder)
        {
            base.OnModelCreating(builder);

            builder.Entity<Audits>().HasQueryFilter(p => p.date_deleted == null);

            builder.Entity<BankAccount>().HasQueryFilter(p => p.date_deleted == null);

            builder.Entity<Beneficiaries>().HasQueryFilter(p => p.date_deleted == null);

            builder.Entity<Employment>().HasQueryFilter(p => p.date_deleted == null);

            builder.Entity<InvestmentName>().HasQueryFilter(p => p.date_deleted == null);

            builder.Entity<Investments>().HasQueryFilter(p => p.date_deleted == null);

            builder.Entity<Permissions>().HasQueryFilter(p => p.date_deleted == null);

            builder.Entity<ProductName>().HasQueryFilter(p => p.date_deleted == null);

            builder.Entity<Roles>().HasQueryFilter(p => p.date_deleted == null);

            builder.Entity<Users>().HasQueryFilter(p => p.date_deleted == null);

            builder.Entity<Customers>().HasQueryFilter(p => p.date_deleted == null);

            // These are raw SQL result types — no tables needed
            builder.Entity<QueryNumCount>().HasNoKey().ToView(null);
            builder.Entity<QueryLabelValue>().HasNoKey().ToView(null);
            builder.Entity<QueryLabelValueCount>().HasNoKey().ToView(null);
            builder.Entity<QueryValueCount>().HasNoKey().ToView(null);
        }

        //Save audit log record when Table record state changes
        public int SaveChanges(Audits? audit = null)
        {
            if (audit == null)
            {
                return base.SaveChanges();
            }
            ChangeTracker.DetectChanges();
            var auditEntries = new List<AuditEntry>();
            foreach (var entry in ChangeTracker.Entries())
            {
                if (
                    entry.Entity is Audits
                    || entry.State == EntityState.Detached
                    || entry.State == EntityState.Unchanged
                )
                    continue;

                var auditEntry = new AuditEntry();
                auditEntries.Add(auditEntry);
                foreach (var property in entry.Properties)
                {
                    if (property.IsTemporary)
                    {
                        // value will be generated by the database, get the value after saving
                        auditEntry.TemporaryProperties.Add(property);
                        continue;
                    }
                    string propertyName = property.Metadata.Name;
                    switch (entry.State)
                    {
                        case EntityState.Added:
                            auditEntry.NewValues[propertyName] = property.CurrentValue;
                            break;
                        case EntityState.Deleted:
                            auditEntry.OldValues[propertyName] = property.OriginalValue;
                            break;
                        case EntityState.Modified:
                            if (property.IsModified)
                            {
                                auditEntry.OldValues[propertyName] = property.OriginalValue;
                                auditEntry.NewValues[propertyName] = property.CurrentValue;
                            }
                            break;
                    }
                }
            }
            // Save audit entities that have all the modifications
            foreach (var auditEntry in auditEntries.Where(_ => !_.HasTemporaryProperties))
            {
                Audits?.Add(auditEntry.ToAudit(audit));
            }

            // keep a list of entries where the value of some properties are unknown at this step
            auditEntries = auditEntries.Where(_ => _.HasTemporaryProperties).ToList();

            var result = base.SaveChanges();

            if (auditEntries != null)
            {
                foreach (var auditEntry in auditEntries)
                {
                    // Get the final value of the temporary properties
                    foreach (var prop in auditEntry.TemporaryProperties)
                    {
                        if (prop.Metadata.IsPrimaryKey())
                        {
                            auditEntry.RecordId = prop.CurrentValue.ToString();
                            continue;
                        }
                        auditEntry.NewValues[prop.Metadata.Name] = prop.CurrentValue;
                    }
                    // Save the Audit entry
                    Audits?.Add(auditEntry.ToAudit(audit));
                }
                SaveChanges();
            }
            return result;
        }
    }
}
